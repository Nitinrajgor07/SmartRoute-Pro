    @staticmethod
    def generate_deliveries_csv(filters=None):
        """Generates UTF-8 encoded formula-safe CSV of filtered delivery records."""
        filters = filters or {}
        query = Delivery.query

        if filters.get('status') and filters['status'] != 'ALL':
            query = query.filter(Delivery.status == filters['status'])
        if filters.get('priority') and filters['priority'] != 'ALL':
            query = query.filter(Delivery.priority == filters['priority'])
        if filters.get('search'):
            term = f"%{filters['search']}%"
            query = query.filter((Delivery.tracking_number.ilike(term)) | (Delivery.customer_name.ilike(term)))

        deliveries = query.order_by(Delivery.id.asc()).all()

        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)
        
        # Header row
        writer.writerow([
            "Tracking Number",
            "Customer Name",
            "Pickup Location",
            "Destination Location",
            "Delivery Date",
            "Priority",
            "Status",
            "Distance (km)"
        ])

        for d in deliveries:
            pickup_name = d.pickup_location.name if d.pickup_location else f"Loc #{d.pickup_location_id}"
            dest_name = d.destination_location.name if d.destination_location else f"Loc #{d.destination_location_id}"
            date_str = d.delivery_date.strftime("%Y-%m-%d") if d.delivery_date else ""
            
            writer.writerow([
                sanitize_csv_cell(d.tracking_number),
                sanitize_csv_cell(d.customer_name),
                sanitize_csv_cell(pickup_name),
                sanitize_csv_cell(dest_name),
                sanitize_csv_cell(date_str),
                sanitize_csv_cell(d.priority),
                sanitize_csv_cell(d.status),
                sanitize_csv_cell(f"{d.distance_km:.2f}" if d.distance_km is not None else "")
            ])

        return output.getvalue().encode('utf-8')

