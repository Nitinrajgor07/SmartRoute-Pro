    @staticmethod
    def generate_my_parcels_csv(customer_email: str):
        """Exports caller's parcels to formula-safe CSV."""
        from sqlalchemy import func
        clean_email = (customer_email or '').strip().lower()
        deliveries = Delivery.query.filter(
            func.lower(Delivery.customer_email) == clean_email
        ).order_by(Delivery.created_at.desc()).all()

        output = io.StringIO()
        writer = csv.writer(output, quoting=csv.QUOTE_MINIMAL)
        writer.writerow([
            "Tracking Number",
            "Status",
            "From",
            "To",
            "Estimated Delivery Time",
            "Last Updated",
            "Created Date"
        ])

        for d in deliveries:
            pickup_name = d.pickup_location.name if d.pickup_location else f"Loc #{d.pickup_location_id}"
            dest_name = d.destination_location.name if d.destination_location else f"Loc #{d.destination_location_id}"
            updated_str = d.updated_at.strftime("%Y-%m-%d %H:%M") if d.updated_at else ""
            created_str = d.created_at.strftime("%Y-%m-%d %H:%M") if d.created_at else ""
            writer.writerow([
                sanitize_csv_cell(d.tracking_number),
                sanitize_csv_cell(d.status),
                sanitize_csv_cell(pickup_name),
                sanitize_csv_cell(dest_name),
                sanitize_csv_cell(d.estimated_delivery_time or "02:00 PM"),
                sanitize_csv_cell(updated_str),
                sanitize_csv_cell(created_str)
            ])

        return output.getvalue().encode('utf-8')

