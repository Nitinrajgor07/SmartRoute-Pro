# 3. CSV Injection Defense Helper
# ==============================================================================

def sanitize_csv_cell(value):
    """Mitigate Spreadsheet Formula Injection (CSV Injection / CWE-1236)."""
    if value is None:
        return ""
    val_str = str(value)
    if val_str and val_str[0] in ('=', '+', '-', '@', '\t', '\r'):
        return f"'{val_str}"
    return val_str


